import { index, integer, sqliteTable, text } from 'drizzle-orm/sqlite-core'
import { ASSET_KINDS, BRAND_SOURCE_TYPES, BRAND_STATUSES } from '../../shared/schemas/brand'
import { ASPECT_RATIOS } from '../../shared/schemas/generation'
import { JOB_STATUSES, JOB_TYPES } from '../../shared/schemas/job'


// brand_id / generation_id are plain nullable columns, not foreign keys: a job must not
// vanish when its brand is deleted (a running job then fails cleanly when it calls back).
export const jobs = sqliteTable(
  'jobs',
  {
    id: text('id').primaryKey(),
    type: text('type', { enum: JOB_TYPES }).notNull(),
    brandId: text('brand_id'),
    generationId: text('generation_id'),
    status: text('status', { enum: JOB_STATUSES }).notNull(),
    stage: text('stage'),
    error: text('error'),
    createdAt: integer('created_at').notNull(),
    startedAt: integer('started_at'),
    finishedAt: integer('finished_at'),
    updatedAt: integer('updated_at').notNull()
  },
  table => [
    index('jobs_status_idx').on(table.status),
    // "latest extraction job of a brand" is looked up on every brand read while extracting
    index('jobs_brand_idx').on(table.brandId, table.createdAt),
    // "latest post job of a generation" is looked up on every generation read
    index('jobs_generation_idx').on(table.generationId, table.createdAt)
  ]
)

export const brands = sqliteTable('brands', {
  id: text('id').primaryKey(),
  name: text('name').notNull(),
  sourceType: text('source_type', { enum: BRAND_SOURCE_TYPES }).notNull(),
  sourceUrl: text('source_url'),
  // The uploaded PDF (brand_assets.kind = 'source_pdf'); plain column to avoid a circular FK.
  sourceAssetId: text('source_asset_id'),
  // BrandDNA as JSON, validated with Zod on write and on read.
  dnaJson: text('dna_json'),
  status: text('status', { enum: BRAND_STATUSES }).notNull(),
  createdAt: integer('created_at').notNull(),
  updatedAt: integer('updated_at').notNull()
})

export const brandAssets = sqliteTable(
  'brand_assets',
  {
    id: text('id').primaryKey(),
    brandId: text('brand_id')
      .notNull()
      .references(() => brands.id, { onDelete: 'cascade' }),
    kind: text('kind', { enum: ASSET_KINDS }).notNull(),
    // Relative to mediaDir, always generated by the server.
    path: text('path').notNull(),
    mime: text('mime').notNull(),
    sizeBytes: integer('size_bytes').notNull(),
    label: text('label'),
    sortOrder: integer('sort_order').notNull().default(0),
    createdAt: integer('created_at').notNull()
  },
  table => [index('brand_assets_brand_idx').on(table.brandId, table.kind, table.sortOrder)]
)

// One row per Studio prompt. It stores no status and no job id: the status is derived from
// the post job (jobs.generation_id), like the status of a brand is derived from its job.
export const generations = sqliteTable(
  'generations',
  {
    id: text('id').primaryKey(),
    brandId: text('brand_id')
      .notNull()
      .references(() => brands.id, { onDelete: 'cascade' }),
    prompt: text('prompt').notNull(),
    aspectRatio: text('aspect_ratio', { enum: ASPECT_RATIOS }).notNull(),
    // JSON array of the product photo ids that were chosen (validated with Zod on read).
    assetIdsJson: text('asset_ids_json').notNull(),
    caption: text('caption'),
    hashtagsJson: text('hashtags_json'),
    // Relative to mediaDir, always generated by the server.
    imagePath: text('image_path'),
    // The video: the script and storyboard arrive while it is still being made, the file at the end.
    // All three are cleared when a new attempt starts. Like the post, the video has no status
    // column: it comes from the latest `video` job of the generation.
    videoScriptJson: text('video_script_json'),
    storyboardPath: text('storyboard_path'),
    videoPath: text('video_path'),
    createdAt: integer('created_at').notNull(),
    updatedAt: integer('updated_at').notNull()
  },
  table => [index('generations_brand_idx').on(table.brandId, table.createdAt)]
)

export type JobRow = typeof jobs.$inferSelect
export type BrandRow = typeof brands.$inferSelect
export type BrandAssetRow = typeof brandAssets.$inferSelect
export type GenerationRow = typeof generations.$inferSelect
